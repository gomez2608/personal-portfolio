import { expect, test } from "vitest";
import type { PostEntry } from "./entries";
import { renderRegistrySource } from "./registry";

function entry(overrides: Partial<PostEntry> = {}): PostEntry {
  return { dir: "a", meta: {}, mdx: "", clipFiles: [], ...overrides };
}

test("renders sorted lazy imports per slug", () => {
  const src = renderRegistrySource([
    entry({ dir: "b", clipFiles: ["clip-2", "clip-1"] }),
    entry({ dir: "a", clipFiles: [] }),
  ]);
  expect(src).toContain('"b": {\n    "clip-1": () => import("@/app/blog/b/clips/clip-1"),\n    "clip-2"');
  expect(src.indexOf('"a"')).toBeLessThan(src.indexOf('"b"'));
  expect(src.startsWith("// Generated by npm run blog:registry")).toBe(true);
});

test("renders an empty registry for zero posts", () => {
  expect(renderRegistrySource([])).toContain("export const clipRegistry: ClipRegistry = {};");
});

test("imports the real ClipComponent type without pulling in the player", () => {
  const src = renderRegistrySource([]);
  expect(src).toContain('import type { ClipComponent } from "@/app/components/blog/clips/clip-types";');
  expect(src).not.toContain("clip-def");
});
