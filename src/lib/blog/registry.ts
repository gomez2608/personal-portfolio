import type { PostEntry } from "./entries";

/**
 * Renders `clip-registry.generated.ts`. Task 6 swaps the placeholder
 * `ClipComponent` line below for the real import from clip-def.
 */
export function renderRegistrySource(entries: PostEntry[]): string {
  const posts = [...entries].sort((a, b) => a.dir.localeCompare(b.dir));
  const body = posts
    .map((p) => {
      const clips = [...p.clipFiles]
        .sort()
        .map((c) => `    ${JSON.stringify(c)}: () => import(${JSON.stringify(`@/app/blog/${p.dir}/clips/${c}`)}),`)
        .join("\n");
      return clips
        ? `  ${JSON.stringify(p.dir)}: {\n${clips}\n  },`
        : `  ${JSON.stringify(p.dir)}: {},`;
    })
    .join("\n");

  return `// Generated by npm run blog:registry — do not edit.
type ClipComponent = import("react").FC & { def: unknown };
type ClipRegistry = Record<string, Record<string, () => Promise<{ default: ClipComponent }>>>;

export const clipRegistry: ClipRegistry = ${body ? `{\n${body}\n}` : "{}"};
`;
}
